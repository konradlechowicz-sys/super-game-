// Builds the 2.0 prototype into one self-contained file, dist/void-blaster-2-proto.html (PixiJS + art inlined),
// to open on a phone. Run from the repo root: node proto2/build.mjs (after python3 proto2/make-assets.py).
import { build } from 'esbuild';
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const dir = 'proto2/assets';
const images = {};
for (const f of readdirSync(dir)) {
  if (!f.endsWith('.webp')) continue;
  images[f.replace('.webp', '')] = `data:image/webp;base64,${readFileSync(`${dir}/${f}`).toString('base64')}`;
}
const ship = JSON.parse(readFileSync(`${dir}/ship.json`, 'utf8'));
writeFileSync('proto2/assets.gen.js', `// generated by proto2/build.mjs\nexport default ${JSON.stringify({ images, ship })};\n`);

const out = await build({
  entryPoints: ['proto2/main.js'], bundle: true, format: 'esm', minify: true, target: ['safari16'], write: false, logLevel: 'warning',
});
const js = out.outputFiles[0].text.replace(/<\/script/g, '<\\/script');
const html = readFileSync('proto2/index.html', 'utf8').replace('<script type="module" src="./main.js"></script>', () => `<script type="module">${js}</script>`);
mkdirSync('dist', { recursive: true });
writeFileSync('dist/void-blaster-2-proto.html', html);
console.log(`Built dist/void-blaster-2-proto.html (${Math.round(html.length / 1024)} KB)`);
