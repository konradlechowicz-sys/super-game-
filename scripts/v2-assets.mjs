// Writes js/v2/assets.gen.js: the 2.0 textures for the 2.0 look (js/v2/renderer.js) as data URLs, so the bundled
// game (app and single-file previews) carries them without extra files. For now (stage 1 of the 2.0 plan) it reuses
// the textures already prepared for the prototype (proto2/assets) and the teaser (teaser/assets).
// Run by scripts/build.mjs and scripts/build-web.mjs.
// With VB_ASSET_DIR set (the web previews, scripts/build-web.mjs), the pictures and the music are copied there as
// separate files and referenced as assets/<file>, so the page itself stays small (an artifact page may have 16 MB).
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';

const OUT = process.env.VB_ASSET_DIR;
if (OUT) { rmSync(OUT, { recursive: true, force: true }); mkdirSync(OUT, { recursive: true }); }
const url = (path, name, mime) => {
  if (!OUT) return `data:${mime};base64,${readFileSync(path).toString('base64')}`;
  copyFileSync(path, `${OUT}/${name}`);
  return `assets/${name}`;
};
const images = {};
const add = (dir, file) => {
  // two folders may share a file name (floor.webp): the copy gets its folder's name in front
  const name = dir === 'proto2/assets' ? file : `${dir.split('/')[0]}-${file}`;
  images[file.replace('.webp', '')] = url(`${dir}/${file}`, name, 'image/webp');
};
for (const f of readdirSync('proto2/assets')) if (/^(ship|enemy|glow|w1|w2|w3|w4|w5)-.*\.webp$/.test(f)) add('proto2/assets', f);
for (const f of ['floor.webp']) add('teaser/assets', f);
// the title screen (js/v2/title.js): the teaser's Earth at night, the Collective's web and the satellites
for (const f of ['earth.webp', 'web.webp', 'emblem.webp']) add('teaser/assets', f);
for (let i = 1; i <= 4; i++) for (const k of ['', '-rewritten']) add('teaser/assets', `sat-${i}${k}.webp`);
const ship = JSON.parse(readFileSync('proto2/assets/ship.json', 'utf8'));
// Phantom and Titan: body + flame and where the nozzles are (proto2/make-ships.py)
const ships = JSON.parse(readFileSync('proto2/assets/ships.json', 'utf8'));
// the world-2 boss, the Landing Citadel: where its parts sit (proto2/make-world2.py)
const citadel = JSON.parse(readFileSync('proto2/assets/w2-boss.json', 'utf8'));
// the world-3 boss, the Moon Spire (proto2/make-world3.py)
const spire = JSON.parse(readFileSync('proto2/assets/w3-boss.json', 'utf8'));
// the world-4 boss, the Red Colossus: where its glows sit (proto2/make-world4.py)
const colossus = JSON.parse(readFileSync('proto2/assets/w4-boss.json', 'utf8'));
// the world-5 boss, the Foundry Mother: where its glows sit (proto2/make-world5.py)
const foundry = JSON.parse(readFileSync('proto2/assets/w5-boss.json', 'utf8'));
writeFileSync('js/v2/assets.gen.js', `// generated by scripts/v2-assets.mjs\nexport default ${JSON.stringify({ images, ship, ships, citadel, spire, colossus, foundry })};\n`);

// recorded 2.0 music (proto2/make-music.py): its own module, so the music loads apart from the textures
const music = JSON.parse(readFileSync('proto2/assets/music.json', 'utf8'));
for (const name of Object.keys(music)) music[name].url = url(`proto2/assets/music-${name}.mp3`, `music-${name}.mp3`, 'audio/mpeg');
writeFileSync('js/v2/music.gen.js', `// generated by scripts/v2-assets.mjs\nexport default ${JSON.stringify(music)};\n`);
