// Writes js/v2/assets.gen.js: the 2.0 textures for the 2.0 look (js/v2/renderer.js) as data URLs, so the bundled
// game (app and single-file previews) carries them without extra files. For now (stage 1 of the 2.0 plan) it reuses
// the textures already prepared for the prototype (proto2/assets) and the teaser (teaser/assets).
// Run by scripts/build.mjs and scripts/build-web.mjs; only the TEST variant loads the 2.0 look.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const images = {};
const add = (dir, file) => { images[file.replace('.webp', '')] = `data:image/webp;base64,${readFileSync(`${dir}/${file}`).toString('base64')}`; };
for (const f of readdirSync('proto2/assets')) if (/^(ship|enemy|glow)-.*\.webp$/.test(f)) add('proto2/assets', f);
for (const f of ['floor.webp', 'harvester.webp', 'h-flame.webp']) add('teaser/assets', f);
const ship = JSON.parse(readFileSync('proto2/assets/ship.json', 'utf8'));
writeFileSync('js/v2/assets.gen.js', `// generated by scripts/v2-assets.mjs\nexport default ${JSON.stringify({ images, ship })};\n`);
