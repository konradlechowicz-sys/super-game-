// Builds the 2.0 teaser into one self-contained file, dist/void-blaster-2-teaser.html (PixiJS, art and fonts
// inlined). Run from the repo root: npm run teaser. Record it to MP4 with npm run teaser:video.
import { build } from 'esbuild';
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { T, MUSIC } from './timeline.js';

// the music cut to the teaser: from MUSIC.start through the gameplay, then a short crossfade onto the track's final
// hit exactly at the title; needs ffmpeg (without it the committed teaser/assets/music.mp3 is used)
const XF = 0.04;
try {
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error',
    '-ss', String(MUSIC.start), '-t', String(T.title + XF), '-i', MUSIC.file,
    '-ss', String(MUSIC.ending - XF / 2), '-t', String(T.end - T.title + 0.5), '-i', MUSIC.file,
    '-filter_complex', `[0][1]acrossfade=d=${XF}:c1=tri:c2=tri,atrim=0:${T.end},afade=t=out:st=${T.end - 0.6}:d=0.6`,
    '-ar', '48000', '-c:a', 'libmp3lame', '-b:a', '192k', 'teaser/assets/music.mp3']);
} catch (e) {
  console.warn(`Could not cut the music (${e.message.split('\n')[0]}); using teaser/assets/music.mp3 as it is`);
}

const images = {};
for (const dir of ['proto2/assets', 'teaser/assets']) {
  for (const f of readdirSync(dir)) {
    if (f.startsWith('floor-tech-ruin')) continue; // the teaser has its own floor
    if (f.endsWith('.webp')) images[f.replace('.webp', '')] = `data:image/webp;base64,${readFileSync(`${dir}/${f}`).toString('base64')}`;
  }
}
const ship = JSON.parse(readFileSync('proto2/assets/ship.json', 'utf8'));
const font = (f) => `data:font/woff2;base64,${readFileSync(`fonts/${f}`).toString('base64')}`;
const fonts = [['Orbitron', font('orbitron.woff2'), '400 900'], ['Rajdhani', font('rajdhani-600.woff2'), '600'], ['Rajdhani', font('rajdhani-700.woff2'), '700']];
// what happens when in the animation (written by teaser/record.mjs), for the page's soundtrack
const events = existsSync('teaser/events.json') ? JSON.parse(readFileSync('teaser/events.json', 'utf8')) : null;
const music = existsSync('teaser/assets/music.mp3') ? `data:audio/mpeg;base64,${readFileSync('teaser/assets/music.mp3').toString('base64')}` : null;
writeFileSync('teaser/assets.gen.js', `// generated by teaser/build.mjs\nexport default ${JSON.stringify({ images, ship, fonts, events, music })};\n`);

const out = await build({
  entryPoints: ['teaser/main.js'], bundle: true, format: 'esm', minify: true, target: ['safari16'], write: false, logLevel: 'warning',
});
const js = out.outputFiles[0].text.replace(/<\/script/g, '<\\/script');
const html = readFileSync('teaser/index.html', 'utf8').replace('<script type="module" src="./main.js"></script>', () => `<script type="module">${js}</script>`);
mkdirSync('dist', { recursive: true });
writeFileSync('dist/void-blaster-2-teaser.html', html);
console.log(`Built dist/void-blaster-2-teaser.html (${Math.round(html.length / 1024)} KB)`);
